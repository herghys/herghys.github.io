#!/usr/bin/env python3
"""Scan PrivacyPolicyCollection/* folders and generate policies.json and policies.js."""

from __future__ import annotations

import json
import re
from datetime import datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
COLLECTION_DIR = ROOT / "PrivacyPolicyCollection"
IGNORED_DIRS = {"styles", "scripts"}

KNOWN_SDKS = [
    ("Google Play Services", r"google\s+play\s+services"),
    ("AdMob", r"\badmob\b"),
    ("Unity", r"\bunity\b"),
    ("Firebase", r"\bfirebase\b"),
    ("Google Analytics", r"google\s+analytics"),
]


def read_text(path: Path) -> str:
    return path.read_text(encoding="utf-8", errors="ignore") if path.exists() else ""


def extract_app_name(slug: str, html: str, md: str) -> str:
    # 1. "built the <strong>App Name</strong> app" or "built the App Name app"
    m = re.search(
        r"built\s+the\s+(?:<[^>]+>\s*)?([^<\n]+?)(?:\s*</[^>]+>)?\s+app\b",
        html,
        re.IGNORECASE,
    )
    if m:
        return " ".join(m.group(1).split())

    # 2. Markdown: "**Application** refers to App Name,"
    m = re.search(r"\*\*Application\*\*\s+refers\s+to\s+([^,\n.]+)", md, re.IGNORECASE)
    if m:
        return " ".join(m.group(1).split())

    # 3. <title>Privacy Policy — App Name | ...</title>
    m = re.search(r"<title>\s*Privacy\s+Policy\s*[-—|:]\s*([^|<]+)", html, re.IGNORECASE)
    if m:
        return " ".join(m.group(1).split())

    # Fallback: humanize folder slug
    return re.sub(r"-Privacy-Policy$", "", slug, flags=re.IGNORECASE).replace("-", " ").strip()


def format_date_label(iso_date: str) -> str:
    try:
        dt = datetime.strptime(iso_date, "%Y-%m-%d")
        return f"{dt.strftime('%b')} {dt.day}, {dt.year}"
    except ValueError:
        return iso_date


def extract_effective_date(html: str, md: str) -> tuple[str, str]:
    combined = f"{html}\n{md}"

    # "effective as of 2026-11-26" (with optional HTML tags)
    m = re.search(
        r"effective\s+as\s+of\s+(?:<[^>]+>)*(\d{4}-\d{2}-\d{2})",
        combined,
        re.IGNORECASE,
    )
    if m:
        iso = m.group(1)
        return iso, format_date_label(iso)

    # "Last updated: November 26, 2026"
    m = re.search(r"Last\s+updated:\s*([A-Za-z]+\s+\d{1,2},\s+\d{4})", combined, re.IGNORECASE)
    if m:
        raw = m.group(1)
        try:
            dt = datetime.strptime(raw, "%B %d, %Y")
            iso = dt.strftime("%Y-%m-%d")
            return iso, format_date_label(iso)
        except ValueError:
            return raw, raw

    return "—", "See full page"


def extract_sdks(html: str, md: str) -> list[str]:
    combined = f"{html}\n{md}"
    return [name for name, pattern in KNOWN_SDKS if re.search(pattern, combined, re.IGNORECASE)]


def build_manifest() -> list[dict]:
    entries: list[dict] = []

    for item in sorted(COLLECTION_DIR.iterdir(), key=lambda p: p.name.lower()):
        if not item.is_dir() or item.name.startswith(".") or item.name in IGNORED_DIRS:
            continue

        html = read_text(item / "index.html")
        md = read_text(item / "PrivacyPolicy.md")
        effective_date, effective_label = extract_effective_date(html, md)
        files = sorted(
            f.name for f in item.iterdir() if f.is_file() and not f.name.startswith(".")
        )

        entries.append(
            {
                "slug": item.name,
                "appName": extract_app_name(item.name, html, md),
                "effectiveDate": effective_date,
                "effectiveLabel": effective_label,
                "sdks": extract_sdks(html, md),
                "files": files,
            }
        )

    # Sort newest effective date first, then alphabetically by appName
    entries.sort(
        key=lambda e: (
            "" if e["effectiveDate"] == "—" else e["effectiveDate"],
            e["appName"].lower(),
        ),
        reverse=True,
    )
    return entries


def main() -> None:
    entries = build_manifest()

    json_path = COLLECTION_DIR / "policies.json"
    json_path.write_text(json.dumps(entries, indent=2) + "\n", encoding="utf-8")

    js_path = COLLECTION_DIR / "policies.js"
    js_content = (
        "// Auto-generated by scripts/generate_privacy_manifest.py — do not edit manually.\n"
        f"window.PRIVACY_POLICIES = {json.dumps(entries, indent=2)};\n"
    )
    js_path.write_text(js_content, encoding="utf-8")

    print(f"Generated {len(entries)} privacy policy entries -> {json_path.name}, {js_path.name}")


if __name__ == "__main__":
    main()
